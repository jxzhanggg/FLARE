class ConvEncoderT(nn.Module):
    def __init__(self,):
        super(ConvEncoderT, self).__init__()
        
        self.frontend_nout = 96
        self.backend_out = 768
        self.frontend3D = nn.Sequential(
            nn.Conv3d(1, self.frontend_nout, kernel_size=(5, 4, 4), stride=(1, 4, 4), padding=(2, 0, 0), bias=False),
            LayerNorm(self.frontend_nout, eps=1e-6, data_format="channels_first2"))

        self.trunk = ConvNeXt(in_chans=1, 
                                kernel_sizes = [7, 7, 5, 3],
                                paddings =  [3, 3, 2, 1],
                                ffn_mult = 4,
                                depths=[2, 2, 2, 2], dims=[self.frontend_nout, 192, 384, self.backend_out])
    
    def forward(self, x):
        B, C, T, H, W = x.size()
        x = self.frontend3D(x)
        Tnew = x.shape[2]
        x = self.threeD_to_2D_tensor(x)
        x = self.trunk(x)
        
        x = x.view(B, Tnew, x.size(1))
        x = x.transpose(1, 2).contiguous()
        return x
    
    def threeD_to_2D_tensor(self, x):
        n_batch, n_channels, s_time, sx, sy = x.shape
        x = x.transpose(1, 2).contiguous()
        return x.reshape(n_batch*s_time, n_channels, sx, sy)



